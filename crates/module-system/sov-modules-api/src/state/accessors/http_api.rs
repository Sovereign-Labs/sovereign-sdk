impl<S: Spec> ApiStateAccessor<S> {
    fn get_from_user_storage(&self, key: &SlotKey) -> Option<SlotValue> {
        if let Some(entry) = self.local_user_writes.get(key) {
            return entry.clone();
        }

        if let Some(entry) = self
            .checkpoint_and_read_txn
            .read_txn
            .get(&(key.clone(), Namespace::User))
        {
            return entry.clone();
        }

        if let Some(changes) = self.uncommitted_changes.as_ref() {
            if let MaybePresentValue::Present(entry) = changes.get(Namespace::User, key) {
                return entry;
            }
        }

        self.checkpoint_and_read_txn
            .state_checkpoint
            .storage()
            .get::<namespaces::User>(key, &self.witness)
    }

    fn get_from_kernel_storage(&self, key: &SlotKey) -> Option<SlotValue> {
        if let Some(entry) = self.local_kernel_writes.get(key) {
            return entry.clone();
        }

        if let Some(entry) = self
            .checkpoint_and_read_txn
            .read_txn
            .get(&(key.clone(), Namespace::Kernel))
        {
            return entry.clone();
        }

        if let Some(changes) = self.uncommitted_changes.as_ref() {
            if let MaybePresentValue::Present(entry) = changes.get(Namespace::Kernel, key) {
                return entry;
            }
        }

        self.checkpoint_and_read_txn
            .state_checkpoint
            .storage()
            .get::<namespaces::Kernel>(key, &self.witness)
    }

    fn get_from_accessory_storage(&self, key: &SlotKey) -> Option<SlotValue> {
        if let Some(write) = self.local_accessory_writes.get(key) {
            return write.value.clone();
        }

        if let Some(write) = self
            .checkpoint_and_read_txn
            .read_txn
            .get(&(key.clone(), Namespace::Accessory))
        {
            return write.clone();
        }

        if let Some(changes) = self.uncommitted_changes.as_ref() {
            if let MaybePresentValue::Present(entry) = changes.get(Namespace::Accessory, key) {
                return entry;
            }
        }

        self.checkpoint_and_read_txn
            .state_checkpoint
            .storage()
            .get_accessory(key)
    }

    fn get_archival_from_user_storage(
        &mut self,
        key: &SlotKey,
        version: Option<SlotNumber>,
    ) -> anyhow::Result<Option<SlotValue>> {
        // First, check if the user has written this value. This allows users to write during eth_call even if they're reading historical state.
        // IMPORTANT: Note that we do *not* read from the state checkpoint during archival queries (it's Arc'd and may contain
        // unrelated data from the current state). However, reading from uncommitted_changes is safe because build_archival_state
        // filters them via ignore_changes_after_height(height) to only contain data at heights <= the requested height.
        if let Some(entry) = self.local_user_writes.get(key) {
            return Ok(entry.clone());
        }
        if let Some(changes) = self.uncommitted_changes.as_ref() {
            if let MaybePresentValue::Present(entry) = changes.get(Namespace::User, key) {
                return Ok(entry);
            }
        }

        self.checkpoint_and_read_txn
            .state_checkpoint
            .storage()
            .get_historical::<namespaces::User>(key, version, &self.witness)
    }

    fn get_archival_from_kernel_storage(
        &mut self,
        key: &SlotKey,
        version: Option<SlotNumber>,
    ) -> anyhow::Result<Option<SlotValue>> {
        // First, check if the kernel has written this value. This allows users to write during eth_call even if they're reading historical state.
        // IMPORTANT: Note that we do *not* read from the state checkpoint during archival queries (it's Arc'd and may contain
        // unrelated data from the current state). However, reading from uncommitted_changes is safe because build_archival_state
        // filters them via ignore_changes_after_height(height) to only contain data at heights <= the requested height.
        if let Some(entry) = self.local_kernel_writes.get(key) {
            return Ok(entry.clone());
        }
        if let Some(changes) = self.uncommitted_changes.as_ref() {
            if let MaybePresentValue::Present(entry) = changes.get(Namespace::Kernel, key) {
                return Ok(entry);
            }
        }

        self.checkpoint_and_read_txn
            .state_checkpoint
            .storage()
            .get_historical::<namespaces::Kernel>(key, version, &self.witness)
    }

    fn get_archival_from_accessory_storage(
        &mut self,
        key: &SlotKey,
        version: Option<SlotNumber>,
    ) -> anyhow::Result<Option<SlotValue>> {
        // First, check if the accessory has written this value. This allows users to write during eth_call even if they're reading historical state.
        if let Some(write) = self.local_accessory_writes.get(key) {
            return Ok(write.value.clone());
        }

        if let Some(changes) = self.uncommitted_changes.as_ref() {
            if let MaybePresentValue::Present(entry) = changes.get(Namespace::Accessory, key) {
                return Ok(entry);
            }
        }

        self.checkpoint_and_read_txn
            .state_checkpoint
            .storage()
            .get_accessory_historical(key, version)
    }
}

/// An error that can occur when creating an [`ApiStateAccessor`].
#[derive(Debug, thiserror::Error, Clone, PartialEq, Eq)]
pub enum ApiStateAccessorError {
    /// The requested height is not accessible.
    #[error("Impossible to get the rollup state at the specified height. The requested height may have been pruned, or it may be in the future. Please ensure you have queried the correct height.")]
    HeightNotAccessible,
}

impl<S: Spec + 'static> ApiStateAccessor<S> {
    /// Creates a new [`ApiStateAccessor`] from a [`StateCheckpoint`] with a gas price of zero at the [`StateCheckpoint::rollup_height_to_access`].
    pub fn new(
        state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>,
        kernel: Arc<dyn KernelWithSlotMapping<S>>,
    ) -> Self {
        let rollup_height = state_checkpoint.rollup_height_to_access();
        Self::new_with_price_and_state_to_access(
            state_checkpoint,
            kernel,
            StateToAccess::RollupHeight(rollup_height),
            <S::Gas as Gas>::Price::ZEROED,
        )
        .expect("Creating an ApiStateCheckpoint without specifying a height is infallible")
    }

    /// Creates a new [`ApiStateAccessor`] which queries all state at the provided slot number.
    pub fn new_archival_with_true_slot_number(
        state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>,
        kernel: Arc<dyn KernelWithSlotMapping<S>>,
        slot_number: SlotNumber,
    ) -> Result<Self, ApiStateAccessorError> {
        let uncommitted_changes = state_checkpoint
            .uncommitted_changes
            .as_ref()
            .map(|c| c.box_clone());
        Self::build_archival_state(
            state_checkpoint,
            uncommitted_changes,
            kernel,
            StateToAccess::TrueSlotNumber(slot_number, None),
        )
    }

    /// Creates a fully initialized [`ApiStateAccessor`] from a [`StateCheckpoint`] and a [`RollupHeight`], if the requested
    /// height is available in storage.
    ///
    /// ## Important
    /// Note that archival state is only available *after* the requested height has been processed by the node. In other words,
    /// state that is *only* soft-confirmed is not available for archival queries.
    pub fn new_archival(
        state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>,
        kernel: Arc<dyn KernelWithSlotMapping<S>>,
        height: RollupHeight,
    ) -> Result<Self, ApiStateAccessorError> {
        let uncommitted_changes = state_checkpoint
            .uncommitted_changes
            .as_ref()
            .map(|c| c.box_clone());
        Self::build_archival_state(
            state_checkpoint,
            uncommitted_changes,
            kernel,
            StateToAccess::RollupHeight(height),
        )
    }

    /// Creates a new [`ApiStateAccessor`] from a [`StateCheckpoint`] with a gas price of zero at the [`StateCheckpoint::rollup_height_to_access`].
    pub fn new_with_true_slot_number_dangerous(
        state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>,
        kernel: Arc<dyn KernelWithSlotMapping<S>>,
        slot_number: SlotNumber,
    ) -> Result<Self, ApiStateAccessorError> {
        Self::new_with_price_and_state_to_access(
            state_checkpoint,
            kernel,
            StateToAccess::TrueSlotNumber(slot_number, None),
            <S::Gas as Gas>::Price::ZEROED,
        )
    }

    /// Converts this [`ApiStateAccessor`] into a [`MeteredApiStateAccessor`], allowing it to be used in authenticator methods.
    pub fn to_provable_reader(self) -> MeteredApiStateAccessor<S> {
        MeteredApiStateAccessor {
            api_state_accessor: self,
        }
    }

    /// A specialized constructor for use in sov-test-utils. This constructor matches the unusual semantic of our testing framework, which expects to see
    /// the *next* visible slot number with the *current* rollup height in the accessor as soon as the slot finishes executing.
    ///
    /// In actual execution, this semantic is not needed because the time between the end of slot N and the start of slot N+1 is neglible. Unfortunately,
    /// our tests are written assuming that all assertions will execute during this miniscule instant of time, so we have to accommodate it for now.
    #[cfg(feature = "test-utils")]
    pub fn new_with_price_and_heights(
        state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>,
        kernel: Arc<dyn KernelWithSlotMapping<S>>,
        rollup_height: RollupHeight,
        visible_slot_number: VisibleSlotNumber,
        gas_price: <S::Gas as Gas>::Price,
    ) -> Result<Self, ApiStateAccessorError> {
        let mut accessor = Self::new_with_price_and_state_to_access(
            state_checkpoint,
            kernel,
            StateToAccess::RollupHeight(rollup_height),
            gas_price,
        )?;
        accessor.visible_slot_number = Some(visible_slot_number);
        Ok(accessor)
    }

    /// Creates a new [`ApiStateAccessor`] that *queries all state at the provided slot number, regardless of whether that slot number is visible*. This should only be used
    /// when the semantics of the call necessitate it. If you're unsure, use [`ApiStateAccessor::new_archival`] and provide a rollup height instead.
    pub fn new_with_price_and_slot_number_dangerous(
        state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>,
        kernel: Arc<dyn KernelWithSlotMapping<S>>,
        slot_number: SlotNumber,
        gas_price: <S::Gas as Gas>::Price,
    ) -> Result<Self, ApiStateAccessorError> {
        Self::new_with_price_and_state_to_access(
            state_checkpoint,
            kernel,
            StateToAccess::TrueSlotNumber(slot_number, None),
            gas_price,
        )
    }

    /// Creates a new [`ApiStateAccessor`] from a [`StateCheckpoint`] with the provided gas price.
    fn new_with_price_and_state_to_access(
        state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>,
        kernel: Arc<dyn KernelWithSlotMapping<S>>,
        state_to_access: StateToAccess,
        gas_price: <S::Gas as Gas>::Price,
    ) -> Result<Self, ApiStateAccessorError> {
        let gas_meter = BasicGasMeter::new_api(gas_price);
        let uncommitted_changes = state_checkpoint
            .uncommitted_changes
            .as_ref()
            .map(|g| g.box_clone());
        let checkpoint_and_read_txn = CheckpointAndReadTxn::new(state_checkpoint);

        let mut out = Self {
            uncommitted_changes,
            witness: Default::default(),
            gas_meter,
            events: Vec::new(),
            temp_cache: TempCache::new(),
            checkpoint_and_read_txn,
            local_kernel_writes: HashMap::new(),
            local_user_writes: HashMap::new(),
            local_accessory_writes: HashMap::new(),
            kernel: kernel.clone(),
            state_to_access,
            visible_slot_number: None,
            safe_true_slot_number_to_use: None,
            encountered_pruning_error: None,
            metrics: StateMetrics::default(),
        };

        (out.safe_true_slot_number_to_use) = match state_to_access {
            // The current slot may not be stored in the `true_slot_number_at_historical_height` map, so we use the previous slot number.
            StateToAccess::RollupHeight(rollup_height) => {
                // If this is a slot that has already been executed, we know the correct true slot number. Use that.
                kernel.true_slot_number_at_historical_height(rollup_height, &mut out)
            }
            StateToAccess::TrueSlotNumber(slot_number, _) => Some(slot_number),
        };

        if let StateToAccess::TrueSlotNumber(slot_number, _) = state_to_access {
            let Some(rollup_height) =
                kernel.true_slot_number_to_rollup_height(slot_number, &mut out)
            else {
                return Err(ApiStateAccessorError::HeightNotAccessible);
            };
            out.state_to_access = StateToAccess::TrueSlotNumber(slot_number, Some(rollup_height));
        }

        let Some(visible_slot_number) = out.lookup_visible_slot_number() else {
            return Err(ApiStateAccessorError::HeightNotAccessible);
        };

        out.visible_slot_number = Some(visible_slot_number);

        Ok(out)
    }

    fn get_uninitialized_empty_accessor(
        state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>,
        kernel: Arc<dyn KernelWithSlotMapping<S>>,
        state_to_access: StateToAccess,
    ) -> Self {
        let uncommitted_changes = state_checkpoint
            .uncommitted_changes
            .as_ref()
            .map(|g| g.box_clone());
        let checkpoint_and_read_txn = CheckpointAndReadTxn::new(state_checkpoint);
        let gas_meter = BasicGasMeter::new_api(<S::Gas as Gas>::Price::ZEROED);
        Self {
            events: Vec::new(),
            gas_meter,
            uncommitted_changes,
            checkpoint_and_read_txn,
            witness: Default::default(),
            local_kernel_writes: HashMap::new(),
            local_user_writes: HashMap::new(),
            local_accessory_writes: HashMap::new(),
            temp_cache: TempCache::new(),
            kernel: kernel.clone(),
            state_to_access,
            safe_true_slot_number_to_use: None,
            // We use MAX here to indicate that the accessor should be allowed to access any value. This is necessary because of the fundamental
            // permissions vs state confusion in our current design of VersionReader - see the comment inline in get_cached for more details.
            visible_slot_number: Some(VisibleSlotNumber::MAX),
            encountered_pruning_error: None,
            metrics: StateMetrics::default(),
        }
    }

    fn lookup_visible_slot_number(&mut self) -> Option<VisibleSlotNumber> {
        match self.state_to_access {
            StateToAccess::RollupHeight(rollup_height) => self
                .kernel
                .clone()
                .rollup_height_to_visible_slot_number(rollup_height, self),
            StateToAccess::TrueSlotNumber(slot_number, _) => {
                let visible_slot_number = VisibleSlotNumber::new_dangerous(slot_number.get());
                Some(visible_slot_number)
            }
        }
    }

    fn clear_caches(&mut self) {
        self.local_kernel_writes = HashMap::new();
        self.local_user_writes = HashMap::new();
        self.local_accessory_writes = HashMap::new();
    }

    /// Sets the gas price for the accessor.
    pub fn set_gas_price(&mut self, gas_price: <S::Gas as Gas>::Price) {
        self.gas_meter.gas_price = gas_price;
    }

    fn build_archival_state(
        state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>,
        uncommitted_changes: Option<Box<dyn StateGetter>>,
        kernel: Arc<dyn KernelWithSlotMapping<S>>,
        height: StateToAccess,
    ) -> Result<Self, ApiStateAccessorError> {
        let latest_true_slot_number = state_checkpoint.storage().latest_version();
        let mut state = ApiStateAccessor::get_uninitialized_empty_accessor(
            state_checkpoint,
            kernel.clone(),
            height,
        );
        state.uncommitted_changes = uncommitted_changes;
        let true_slot_number = match height {
            // If the caller provided a rollup height, find the associated true slot number.
            StateToAccess::RollupHeight(height) => {
                if let Some(true_slot_number) =
                    kernel.true_slot_number_at_historical_height(height, &mut state)
                {
                    true_slot_number
                } else if let Some(max_height) = state
                    .uncommitted_changes
                    .as_ref()
                    .and_then(|c| c.latest_rollup_height())
                {
                    // If the requested height is greater than our uncommitted changes, we can't access it.
                    if max_height < height {
                        return Err(ApiStateAccessorError::HeightNotAccessible);
                    }
                    // Use our latest slot number from storage as a safe commit.
                    // (Anything not already in storage by that point will be in the uncommitted changes,
                    // which are pruned to the requested height below.)
                    latest_true_slot_number
                } else if height == kernel.current_rollup_height(&mut state) {
                    // There's a tricky case here where the height exists in storage but the true slot number is not available via the kernel yet.
                    // This is because the true slot number mapping is updated at the beginning of the next slot, but the rest of the values are written
                    // at the end of the current slot.
                    //
                    // Since the ApiStateAccessor has empty caches right now, we can check if we're in this case by checking whether the requested height is equal to the current rollup height
                    // as reported by the kernel. (Recall that, since the caches are empty, the "current_rollup_height" value reported by the kernel is the value stored at S::Storage::latest_version.)
                    latest_true_slot_number
                } else {
                    return Err(ApiStateAccessorError::HeightNotAccessible);
                }
            }
            StateToAccess::TrueSlotNumber(slot_number, _) => {
                if slot_number > latest_true_slot_number {
                    return Err(ApiStateAccessorError::HeightNotAccessible);
                }
                slot_number
            }
        };

        // If the caller provided a true slot number, find the associated rollup height.
        let rollup_height = match height {
            StateToAccess::RollupHeight(rollup_height)
            | StateToAccess::TrueSlotNumber(_, Some(rollup_height)) => rollup_height,
            StateToAccess::TrueSlotNumber(slot_number, None) => {
                let result = kernel.true_slot_number_to_rollup_height(slot_number, &mut state);
                if state.encountered_pruning_error.is_some() {
                    return Err(ApiStateAccessorError::HeightNotAccessible);
                }
                result.unwrap_or_else(|| panic!("Visible slot number not available for slot_number {slot_number}, but that slot exists in storage. This is a bug. Please report it."))
            }
        };
        // Prune uncommitted changes to only contain data at heights <= the requested rollup height.
        // This ensures archival reads never return values from newer uncommitted blocks.
        if let Some(c) = state.uncommitted_changes.as_mut() {
            c.ignore_changes_after_height(rollup_height);
        }
        // Use the slot number to find the visible slot number.
        let result = kernel.visible_slot_number_at(true_slot_number, &mut state);

        let Some(visible_slot_number) = result else {
            panic!("Visible slot number not available at slot number {true_slot_number}, but that height exist in storage. This is a bug. Please report it.");
        };
        // Use the rollup height to find the base fee per gas.
        let result = kernel.base_fee_per_gas_at(rollup_height, &mut state);
        let Some(base_fee_per_gas) = result else {
            panic!("Base fee per gas not available at height {rollup_height}, but that height exist in storage. This is a bug. Please report it.");
        };
        state.visible_slot_number = Some(visible_slot_number);
        state.safe_true_slot_number_to_use = Some(true_slot_number);
        state.set_gas_price(base_fee_per_gas);
        // Run a test query at the requested height to ensure that the state is accessible.
        let test_key = SlotKey::from_slice(b"test-key");
        let _test_query_result = state.get_value(
            namespaces::User::NAMESPACE,
            &test_key,
            &mut StateAccessMetric::new_read(), // We throw away the metric from this test query because it should almost always be cached and wasn't requested by the user
        );
        if state.encountered_pruning_error.is_some() {
            return Err(ApiStateAccessorError::HeightNotAccessible);
        }

        // Clear out any new values that were put in cache during initialization. Otherwise, we'd incorrectly estimate gas costs for
        // the first accesses to those values since they would be incorrectly shown as cached.
        state.clear_caches();
        Ok(state)
    }

    /// Clones the accessor for use in RPC contexts, dropping any local writes that were made to the accessor.
    pub fn clone_without_local_writes(&self) -> ApiStateAccessor<S> {
        ApiStateAccessor {
            witness: Default::default(),
            events: Vec::new(),
            gas_meter: self.gas_meter.clone(),
            local_kernel_writes: HashMap::new(),
            local_user_writes: HashMap::new(),
            local_accessory_writes: HashMap::new(),
            uncommitted_changes: self.uncommitted_changes.as_ref().map(|c| c.box_clone()),
            temp_cache: TempCache::new(),
            checkpoint_and_read_txn: self.checkpoint_and_read_txn.clone(),
            kernel: self.kernel.clone(),
            state_to_access: self.state_to_access,
            visible_slot_number: self.visible_slot_number,
            safe_true_slot_number_to_use: self.safe_true_slot_number_to_use,
            encountered_pruning_error: None,
            metrics: StateMetrics::default(),
        }
    }

    /// Returns a new accessor which accesses the rollup at the specified `height`.
    /// The gas price contained in the accessor is set to the base fee per gas at the specified height.
    pub fn get_archival_state(
        &self,
        height: RollupHeight,
    ) -> Result<ApiStateAccessor<S>, ApiStateAccessorError> {
        Self::build_archival_state(
            self.checkpoint_and_read_txn.state_checkpoint.clone(),
            self.uncommitted_changes.as_ref().map(|c| c.box_clone()),
            self.kernel.clone(),
            StateToAccess::RollupHeight(height),
        )
    }

    /// Returns an accessor suitable for `finalized`-tag RPC reads.
    ///
    /// The checkpoint carries explicit finalized policy because both preferred
    /// and standard sequencer modes can temporarily have the same finalized
    /// slot number while requiring different behavior:
    /// - preferred mode: finalized should follow the storage head;
    /// - standard mode: finalized should use the node-reported finalized slot.
    ///
    /// We therefore branch on policy, not on slot-number equality.
    pub fn build_finalized_state(&self) -> Result<ApiStateAccessor<S>, ApiStateAccessorError> {
        match self
            .checkpoint_and_read_txn
            .state_checkpoint
            .finalized_slot_policy()
        {
            FinalizedSlotPolicy::TrackStorageHead => Ok(self.clone_without_local_writes()),
            FinalizedSlotPolicy::UseExplicit(slot_number) => {
                Self::new_archival_with_true_slot_number(
                    self.checkpoint_and_read_txn.state_checkpoint.clone(),
                    self.kernel.clone(),
                    slot_number,
                )
            }
        }
    }

    /// Returns the latest finalized slot number available to this accessor.
    pub fn latest_finalized_slot_number(&self) -> SlotNumber {
        self.checkpoint_and_read_txn
            .state_checkpoint
            .latest_finalized_slot_number()
    }

    /// Get the true slot number being used for queries.
    #[cfg(feature = "test-utils")]
    pub fn true_slot_number_to_use(&self) -> SlotNumber {
        self.safe_true_slot_number_to_use.unwrap()
    }
}

impl<S: Spec> crate::state::accessors::StateMetricsProvider for ApiStateAccessor<S> {
    fn metrics(&mut self) -> &mut StateMetrics {
        &mut self.metrics
    }
}

impl<S: Spec> VersionReader for ApiStateAccessor<S> {
    fn current_visible_slot_number(&self) -> VisibleSlotNumber {
        self.visible_slot_number
            .expect("Visible slot number must be set during accessor initialization")
    }

    fn max_allowed_slot_number_to_access(&self) -> SlotNumber {
        self.current_visible_slot_number().as_true()
    }

    fn rollup_height_to_access(&self) -> RollupHeight {
        match self.state_to_access {
            StateToAccess::RollupHeight(rollup_height) => rollup_height,
            StateToAccess::TrueSlotNumber(_slot_number, Some(rollup_height)) => rollup_height,
            StateToAccess::TrueSlotNumber(slot_number, None) => {
                panic!("Rollup height not cached for slot number {slot_number}, but that slot exists in storage. This is a bug in ApiStateAccessor initialization. Please report it.");
            }
        }
    }
}

/// A wrapper around [`ApiStateAccessor`] that implements ProvableStateReader for both namespaces.
pub struct MeteredApiStateAccessor<S: Spec> {
    pub api_state_accessor: ApiStateAccessor<S>,
}

