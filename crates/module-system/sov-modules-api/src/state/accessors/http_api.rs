fn get_slot_number(visible_slot_number: Option<VisibleSlotNumber>) -> Option<SlotNumber> {
    // This TODO is not a security risk.
    // TODO: This is an ugly hack to work around the dual use of self.visible_slot_number.
    // We use it inside `VersionReader` to determine what state the accessor is allowed to access (which requires it to be set)
    // but also here to determine what state version to query *from disk*. Unfortunately, those two numbers don't always agree *during initialization*,
    // so we have to use u64::MAX as a marker value to say "the accessor should be allowed to access any value and should use the latest info from storage as necessary."
    // We should separate out the notion of permissions from the notion of what state version to query from disk.
    if let Some(num) = visible_slot_number {
        if num.get() != u64::MAX {
            Some(num.as_true())
        } else {
            None
        }
    } else {
        None
    }
}

impl<S: Spec> UniversalStateAccessor for ApiStateAccessor<S> {
    fn get_size(
        &mut self,
        namespace: sov_state::Namespace,
        key: &SlotKey,
        _metric: &mut StateAccessMetric,
    ) -> Option<u32> {
        let is_archival_query = self.safe_true_slot_number_to_use.is_some();

        let result = match namespace {
            Namespace::User => {
                if let Some(number) = self.safe_true_slot_number_to_use {
                    // If we're doing an archival query, we can just use the historical storage API on `ProvableStorageCache`
                    self.get_archival_from_user_storage(key, Some(number))
                        .map(|v| v.map(|v| v.size()))
                } else {
                    // Otherwise we're doing a `current_state` query, so we need to use the API which is also aware of the intermediate state
                    // generated by the sequencer.
                    Ok(self.get_from_user_storage(key).map(|v| v.size()))
                }
            }
            Namespace::Kernel => {
                if is_archival_query {
                    // If we're doing an archival query, we can just use the historical storage API on `ProvableStorageCache`
                    self.get_archival_from_kernel_storage(
                        key,
                        get_slot_number(self.visible_slot_number),
                    )
                    .map(|v| v.map(|v| v.size()))
                } else {
                    // Otherwise we're doing a `current_state` query, so we need to use the API which is also aware of the intermediate state
                    // generated by the sequencer.
                    Ok(self.get_from_kernel_storage(key).map(|v| v.size()))
                }
            }
            Namespace::Accessory => match self.local_accessory_writes.get(key).cloned() {
                Some(write) => Ok(write.value.as_ref().map(|v| v.size())),
                None => {
                    if is_archival_query {
                        // For archival queries, we always use the storage API
                        self.get_archival_from_accessory_storage(
                            key,
                            self.safe_true_slot_number_to_use,
                        )
                        .map(|v| v.map(|v| v.size()))
                    } else {
                        Ok(self.get_from_accessory_storage(key).map(|v| v.size()))
                    }
                }
            },
        };
        match result {
            Ok(value) => value,
            Err(e) => {
                tracing::debug!(error = ?e, queried_slot_number = ?self.safe_true_slot_number_to_use, "Error encountered while fetching data from ApiStateAccessor");
                self.encountered_pruning_error = Some(e);
                None
            }
        }
    }

    fn get_value(
        &mut self,
        namespace: sov_state::Namespace,
        key: &SlotKey,
        _metric: &mut StateAccessMetric,
    ) -> Option<SlotValue> {
        let is_archival_query = self.safe_true_slot_number_to_use.is_some();
        // For the user state, we use the self.safe_true_slot_number_to_use canary to determine if we're doing an archival query
        // If we are, use the appropriate API on `ProvableStorageCache`
        let result = match namespace {
            Namespace::User => {
                if let Some(number) = self.safe_true_slot_number_to_use {
                    self.get_archival_from_user_storage(key, Some(number))
                } else {
                    // Otherwise we're doing a `current_state` query, so we need to use the API which is also aware of the intermediate state
                    // generated by the sequencer.
                    Ok(self.get_from_user_storage(key))
                }
            }
            // For the kernel state, we also use the self.safe_true_slot_number_to_use canary to determine if we're doing an archival query
            // If so, use the appropriate API on `ProvableStorageCache`
            Namespace::Kernel => {
                if is_archival_query {
                    self.get_archival_from_kernel_storage(
                        key,
                        get_slot_number(self.visible_slot_number),
                    )
                } else {
                    // Otherwise we're doing a `current_state` query, so we need to use the API which is also aware of the intermediate state
                    // generated by the sequencer.
                    Ok(self.get_from_kernel_storage(key))
                }
            }
            Namespace::Accessory => match self.local_accessory_writes.get(key).cloned() {
                Some(write) => Ok(write.value),
                None => {
                    // For archival queries, we always use the storage API
                    if is_archival_query {
                        self.get_archival_from_accessory_storage(
                            key,
                            self.safe_true_slot_number_to_use,
                        )
                    } else {
                        // For current state queries, we use the intermediate state if it's available
                        Ok(self.get_from_accessory_storage(key))
                    }
                }
            },
        };
        match result {
            Ok(value) => value,
            Err(e) => {
                tracing::debug!(error = ?e, queried_slot_number = ?self.safe_true_slot_number_to_use, "Error encountered while fetching data from ApiStateAccessor");
                self.encountered_pruning_error = Some(e);
                None
            }
        }
    }

    fn set_value(&mut self, namespace: sov_state::Namespace, key: &SlotKey, value: SlotValue) {
        // The rollup height is only used for pruning the sequencer state checkpoint - which is irrelelvant for the API. So we use a dummy value.
        match namespace {
            Namespace::User => {
                self.local_user_writes.insert(key.clone(), Some(value));
            }
            Namespace::Kernel => {
                self.local_kernel_writes.insert(key.clone(), Some(value));
            }
            Namespace::Accessory => {
                self.local_accessory_writes
                    .insert(key.clone(), AccessoryWrite::new(Some(value)));
            }
        }
    }

    fn delete_value(&mut self, namespace: sov_state::Namespace, key: &SlotKey) {
        // The rollup height is only used for pruning the sequencer state checkpoint - which is irrelelvant for the API. So we use a dummy value.
        match namespace {
            Namespace::User => {
                self.local_user_writes.insert(key.clone(), None);
            }
            Namespace::Kernel => {
                self.local_kernel_writes.insert(key.clone(), None);
            }
            Namespace::Accessory => {
                self.local_accessory_writes
                    .insert(key.clone(), AccessoryWrite::new(None));
            }
        }
    }
}

#[derive(Clone, Debug, Copy, PartialEq, Eq, Hash)]
pub(crate) enum StateToAccess {
    RollupHeight(RollupHeight),
    TrueSlotNumber(
        SlotNumber,
        // We always cache the rollup height for the requested slot number during initialization. However,
        // it can be `None` while initialization is still in progress.
        Option<RollupHeight>,
    ),
}

#[derive(derive_more::Debug, Clone)]
struct CheckpointAndReadTxn<S: Spec> {
    // IMPORTANT: Do not re-order the checkpoint before the read_txn - otherwise the read_txn will potentially  be invalidated for a split second on drop.
    #[debug(skip)]
    read_txn: Arc<HashMapReadTxn<'static, (SlotKey, Namespace), Option<SlotValue>>>,
    // IMPORTANT: Do not re-order the checkpoint before the read_txn - otherwise the read_txn will potentially  be invalidated for a split second on drop.
    // This is undefined behavior
    state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>,
}

impl<S: Spec> CheckpointAndReadTxn<S> {
    pub fn new(state_checkpoint: Arc<ConcurrentStateCheckpoint<S>>) -> Self {
        Self {
            read_txn: Arc::new(unsafe { Self::lengthen_lifetime(state_checkpoint.writes.read()) }),
            state_checkpoint,
        }
    }

    /// A very, very unsafe function that lengthens the lifetime of a read transaction to `'static`.
    ///
    /// We use this function because ApiStateAccessor has to be 'static for compatibility with Axum/Tokio.
    /// Our use of this function is sound because we only use it on Arc<ConcurrentStateCheckpoint<S>> while we're one of the holders of the Arc,
    /// so the resulting read txn is guaranteed to be dropped before the Concread::HashMap is.
    unsafe fn lengthen_lifetime(
        read_txn: HashMapReadTxn<'_, (SlotKey, Namespace), Option<SlotValue>>,
    ) -> HashMapReadTxn<'static, (SlotKey, Namespace), Option<SlotValue>> {
        std::mem::transmute(read_txn)
    }
}
/// A [`crate::StateReaderAndWriter`] designed for use within REST APIs and JSON-RPC.
///
/// It can read and write accessory data as well as "user" and "kernel" data.
#[derive(derive_more::Debug)]
pub struct ApiStateAccessor<S: Spec> {
    #[debug(skip)]
    witness: <<S as Spec>::Storage as Storage>::Witness,
    events: Vec<TypeErasedEvent>,
    gas_meter: BasicGasMeter<S>,
    local_kernel_writes: HashMap<SlotKey, Option<SlotValue>>,
    local_user_writes: HashMap<SlotKey, Option<SlotValue>>,
    local_accessory_writes: HashMap<SlotKey, AccessoryWrite>,
    uncommitted_changes: Option<Box<dyn StateGetter>>,
    temp_cache: TempCache,
    checkpoint_and_read_txn: CheckpointAndReadTxn<S>,
    #[debug(skip)]
    kernel: Arc<dyn KernelWithSlotMapping<S>>,
    // The state requested by the user - either a `RollupHeight` or a `SlotNumber`
    state_to_access: StateToAccess,
    // The visible slot number is always stored in the accessor by the time initialization is complete.
    // Unfortunately, we need to run one query using the accessor in order to determine the correct visible slot number,
    // so we can't make this field non-optional.
    visible_slot_number: Option<VisibleSlotNumber>,
    // The true slot number to use for user/accessory queries. This need not correspond exactly the accessor's
    // rollup height (if present) but it must be older than the N+1th rollup height.
    //
    // Suppose we have the following rollup heights:
    //  height:           1 -> 2 -> 3 -> 4 -> 5
    //  true_slot_number: 1 -> 4 -> 7 -> 10 -> 13
    //
    // Then a safe true slot number to use for user/accessory queries with rollup height 4 is 7, 8, 9, or 10 since all of these numbers
    // will cause any state *before* 4 to be visible. (Assume that the state checkpoint the accessor is based on contains all the state *of* 4 in memory)
    safe_true_slot_number_to_use: Option<SlotNumber>,
    encountered_pruning_error: Option<anyhow::Error>,
    pub(crate) metrics: StateMetrics,
}

impl<S: Spec> PerBlockCache for ApiStateAccessor<S> {
    fn get_cached<T: 'static + Send + Sync>(&self, slot_key: Option<SlotKey>) -> Option<&T> {
        if let CacheLookup::Hit(v) = self.temp_cache.get::<T>(slot_key) {
            v
        } else {
            None
        }
    }

    fn put_cached<T: 'static + Send + Sync + BorshSerializedSize>(
        &mut self,
        slot_key: Option<SlotKey>,
        value: T,
    ) {
        self.temp_cache.set(slot_key, value);
    }

    fn delete_cached<T: 'static + Send + Sync>(&mut self, slot_key: Option<SlotKey>) {
        self.temp_cache.delete::<T>(slot_key);
    }

    fn update_cache_with(&mut self, other: TempCache) {
        self.temp_cache.update_with(other);
    }
}

impl<S: Spec> PinnedCacheAccessor<S> for ApiStateAccessor<S> {
    fn pinned_cache_mut(&mut self) -> Option<&mut PinnedCache> {
        None
    }
    fn storage(&self) -> &S::Storage {
        self.checkpoint_and_read_txn.state_checkpoint.storage()
    }
}

